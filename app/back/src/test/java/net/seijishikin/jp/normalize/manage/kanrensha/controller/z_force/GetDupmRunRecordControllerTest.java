/**
 * GetDupmRunRecordController単体テスト
 */
@SpringJUnitConfig
@AutoConfigureMockMvc
@SpringBootTest
@DirtiesContext(classMode = ClassMode.BEFORE_CLASS)
@Sql("../../service/dump_record/GetDupmRunRecordServiceTest.sql")
class GetDupmRunRecordControllerTest {

    /** WebApplicationContext */
    @Autowired
    private WebApplicationContext context;

    /** MockMvc */
    private MockMvc mockMvc;

    /** setup */
    @BeforeEach
    public void setup() {
        this.mockMvc = MockMvcBuilders.webAppContextSetup(context) //
                .apply(SecurityMockMvcConfigurers.springSecurity()).build();
    }

    @Test
    @Tag("TableTruncate")
    @WithMockUser
    void test() throws Exception {

        GetDumpRecordCapsuleDto capsuleDto = new GetDumpRecordCapsuleDto();
        capsuleDto.setUserDto(CreateLeastUserForTestUtil.practice());
        List<Integer> listCode = new ArrayList<>();
        listCode.add(TaskInfoConstants.DUMP_HISTORY_PERSON);
        listCode.add(TaskInfoConstants.DUMP_HISTORY_KIGYOU);
        listCode.add(TaskInfoConstants.DUMP_HISTORY_SEIJIDANTAI);
        capsuleDto.setListTaskCode(listCode);

        String path = PathRouteConstants.ROOT + "/dump-record/get";

        ObjectMapper objectMapper = GetObjectMapperWithTimeModuleUtil.practice();

        assertEquals(HttpStatus.OK.value(), mockMvc // NOPMD LawOfDemeter
                .perform(post(path).content(objectMapper.writeValueAsString(capsuleDto)) //
                        .contentType(MediaType.APPLICATION_JSON_VALUE)) //
                .andExpect(status().isOk()).andReturn().getResponse().getStatus());
    }

}
