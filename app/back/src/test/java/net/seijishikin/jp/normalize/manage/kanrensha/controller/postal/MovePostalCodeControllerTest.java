/**
 * MovePostalCodeController単体テスト
 */
@SpringJUnitConfig
@AutoConfigureMockMvc
@SpringBootTest(webEnvironment = WebEnvironment.RANDOM_PORT)
@DirtiesContext(classMode = ClassMode.BEFORE_CLASS)
@Sql("../../service/postal/WrapMovePostalcodeRsdtServiceTest.sql")
class MovePostalCodeControllerTest {

    /** MockMvc */
    @Autowired
    private MockMvc mockMvc;

    @Test
    @Tag("TableTruncate")
    @WithMockUser
    void test() throws Exception {

        MovePostalCodeCapsuleDto capsuleDto = new MovePostalCodeCapsuleDto();
        final String lgCode = "042072";
        // 9811201→1112222
        capsuleDto.setLgCode(lgCode);
        capsuleDto.setPostalOld1("981");
        capsuleDto.setPostalOld2("1201");
        capsuleDto.setPostalNew1("111");
        capsuleDto.setPostalNew2("2222");
        capsuleDto.setUserDto(CreateLeastUserForTestUtil.practice());

        String path = PathRouteConstants.ROOT + "/postal-code/move";

        ObjectMapper objectMapper = GetObjectMapperWithTimeModuleUtil.practice();

        assertEquals(HttpStatus.OK.value(), mockMvc // NOPMD LawOfDemeter
                .perform(post(path).content(objectMapper.writeValueAsString(capsuleDto)) //
                        .contentType(MediaType.APPLICATION_JSON_VALUE)) //
                .andExpect(status().isOk()).andReturn().getResponse().getStatus());
    }

}
